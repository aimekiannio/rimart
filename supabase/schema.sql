create extension if not exists pgcrypto;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  description text not null default '',
  price integer not null check (price > 0),
  category text not null check (category in ('Clothing', 'Accessories', 'Electronics')),
  image text not null,
  badge text not null default 'New',
  stock integer not null default 0 check (stock >= 0),
  published boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique,
  customer_name text not null,
  phone text not null,
  email text,
  address text not null,
  city text not null,
  state text not null,
  pincode text not null,
  total integer not null default 0 check (total >= 0),
  payment_method text not null default 'cod' check (payment_method = 'cod'),
  status text not null default 'new' check (status in ('new', 'confirmed', 'shipped', 'delivered', 'cancelled')),
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  unit_price integer not null check (unit_price > 0),
  quantity integer not null check (quantity > 0)
);

alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
grant all on table public.products, public.orders, public.order_items to service_role;
grant usage, select on all sequences in schema public to service_role;

-- Prices and stock are checked on the server; this transaction locks each
-- product row before reserving inventory to avoid overselling.
create or replace function public.create_cash_order(
  p_customer_name text,
  p_phone text,
  p_email text,
  p_address text,
  p_city text,
  p_state text,
  p_pincode text,
  p_items jsonb
)
returns table(order_number text, total integer)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_order_id uuid;
  v_order_number text := 'GAL-' || to_char(now(), 'YYMMDD') || '-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 6));
  v_line record;
  v_product public.products%rowtype;
  v_total integer := 0;
begin
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 30 then
    raise exception 'Add between 1 and 30 products to your order.';
  end if;
  if length(trim(p_customer_name)) = 0 or length(trim(p_phone)) = 0
    or length(trim(p_address)) = 0 or length(trim(p_city)) = 0
    or length(trim(p_state)) = 0 or length(trim(p_pincode)) = 0 then
    raise exception 'Complete the delivery details before ordering.';
  end if;

  insert into public.orders (order_number, customer_name, phone, email, address, city, state, pincode)
  values (v_order_number, trim(p_customer_name), trim(p_phone), nullif(trim(p_email), ''), trim(p_address), trim(p_city), trim(p_state), trim(p_pincode))
  returning id into v_order_id;

  for v_line in
    select product_id, sum(quantity)::integer as quantity
    from jsonb_to_recordset(p_items) as item(product_id bigint, quantity integer)
    group by product_id
  loop
    if v_line.quantity is null or v_line.quantity < 1 or v_line.quantity > 20 then
      raise exception 'Each product quantity must be between 1 and 20.';
    end if;
    select * into v_product from public.products
      where id = v_line.product_id and published = true for update;
    if not found then raise exception 'A product in your cart is no longer available.'; end if;
    if v_product.stock < v_line.quantity then
      raise exception 'Not enough stock for %.', v_product.name;
    end if;

    update public.products set stock = stock - v_line.quantity where id = v_product.id;
    insert into public.order_items (order_id, product_id, product_name, unit_price, quantity)
    values (v_order_id, v_product.id, v_product.name, v_product.price, v_line.quantity);
    v_total := v_total + v_product.price * v_line.quantity;
  end loop;

  if v_total < 1 then raise exception 'Your order total must be greater than zero.'; end if;
  update public.orders set total = v_total where id = v_order_id;
  return query select v_order_number, v_total;
end;
$$;

revoke all on function public.create_cash_order(text, text, text, text, text, text, text, jsonb) from public, anon, authenticated;
grant execute on function public.create_cash_order(text, text, text, text, text, text, text, jsonb) to service_role;

create or replace function public.update_order_status(p_order_id uuid, p_status text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_order public.orders%rowtype;
  v_item record;
begin
  if p_status not in ('new', 'confirmed', 'shipped', 'delivered', 'cancelled') then
    raise exception 'Choose a valid order status.';
  end if;
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then raise exception 'Order not found.'; end if;
  if v_order.status = 'cancelled' and p_status <> 'cancelled' then
    raise exception 'A cancelled order cannot be reopened. Create a new order instead.';
  end if;
  if v_order.status <> 'cancelled' and p_status = 'cancelled' then
    for v_item in select product_id, quantity from public.order_items where order_id = p_order_id and product_id is not null
    loop
      update public.products set stock = stock + v_item.quantity where id = v_item.product_id;
    end loop;
  end if;
  update public.orders set status = p_status where id = p_order_id;
end;
$$;

revoke all on function public.update_order_status(uuid, text) from public, anon, authenticated;
grant execute on function public.update_order_status(uuid, text) to service_role;

